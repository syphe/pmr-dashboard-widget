-- Local development entry point. Load this file through the GIANTS debugger.
DashboardMod = DashboardMod or {}
DashboardMod.root = DashboardMod.root or g_currentModDirectory
assert(type(DashboardMod.root)=='string','Run local_bootstrap.lua generated by tools/setup_assets.py')
source('dataS/s4sGame/scripts/main.lua')

for _,file in ipairs({'profile_registry.lua','catalog/vehicles.lua','assets/installed.lua'}) do
    source(DashboardMod.root..file)
end
assert(DashboardMod.installedVehicleIds,'Run tools/setup_assets.py to prepare local game assets')
for _,file in ipairs(DashboardMod.installedAssetSources) do source(DashboardMod.root..file) end
DashboardMod.profiles={}
for _,id in ipairs({'Toyota_Supra_GT4','Ford_Mustang_V8Supercar_2024','Chevrolet_Camaro_V8Supercar_2024'}) do
    if DashboardMod.installedVehicleIds[id] then source(DashboardMod.root..'profiles/'..id..'.lua') end
end
for _,entry in ipairs(DashboardMod.catalog) do
    if DashboardMod.installedVehicleIds[entry.id] then source(DashboardMod.root..entry.file) end
end
source(DashboardMod.root..'dashboard_widget.lua')
DashboardMod.install()
